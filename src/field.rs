//! 아레나와 같은 모양으로 비워 둔다(컷씬 좌표가 화면 기준). 기호는 map.rs.
//!
//! 지금은 시험 필드 하나(800×480): 꽃 핀 들판 → 남쪽 굴 입구(D). 저장 지점(S) 둘.

use crate::map::{self, Parsed};

pub const ROWS: [&str; 30] = [
    "##################################################",
    "##################################################",
    "#.................#######........................#",
    "#.....S..o.....o..#######.......R..........s.....#",
    "#................................................#",
    "#.P.................................c.........T..#",
    "#................................................#",
    "#.........................R......................#",
    "#...o.....o.....o.........................c......#",
    "#.................#######........................#",
    "#######.....###############....########.....######",
    "#######.....###############....########.....######",
    "#.....T.......................................R..#",
    "#.........c......................s...............#",
    "#.....................R..........................#",
    "#....R.......................T...................#",
    "#.........................................c......#",
    "#..............######............................#",
    "#..............######.........######.............#",
    "#####.....#############.......######....##########",
    "#####.....#############.......######....##########",
    "#.....................................s..........#",
    "#....c.........R.................................#",
    "#.............................T...........#####..#",
    "#..........T..............................#####..#",
    "#......................c.........R.........D.....#",
    "#................................................#",
    "#..........S.....................................#",
    "##################################################",
    "##################################################",
];

pub fn parse() -> Parsed {
    map::parse(&ROWS)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::map::Cell;

    #[test]
    fn field_has_start_entrance_and_save() {
        let p = parse();
        assert!(!p.grid.find(Cell::Entrance).is_empty());
        assert!(!p.grid.find(Cell::Save).is_empty());
        assert!(!p.enemies.is_empty());
        // 오프닝 컷씬이 걷는 줄(y≈90, x 30..300)은 바닥이어야 한다.
        for x in (32..300).step_by(16) {
            let (cx, cy) = (x / 16, 90 / 16);
            assert_eq!(p.grid.get(cx, cy), Cell::Floor, "x={x}");
        }
    }
}
